import re, subprocess

with open("/tmp/deepseek_alpha.js", "r", encoding="utf-8") as f:
    alpha_raw = f.read()
with open("/tmp/deepseek_beta.js", "r", encoding="utf-8") as f:
    beta1_raw = f.read()
with open("/tmp/deepseek_beta_part2.js", "r", encoding="utf-8") as f:
    beta2_raw = f.read()
with open("/tmp/deepseek_gamma.js", "r", encoding="utf-8") as f:
    gamma_raw = f.read()

def strip_markdown(text):
    lines = text.strip().splitlines()
    if lines and lines[0].strip().startswith("```"):
        lines = lines[1:]
    if lines and lines[-1].strip().startswith("```"):
        lines = lines[:-1]
    return "\n".join(lines)

alpha = strip_markdown(alpha_raw)
beta1 = strip_markdown(beta1_raw)
beta2 = strip_markdown(beta2_raw)
gamma = strip_markdown(gamma_raw)

# In beta1, cut off before incomplete drawCAT6020B
cat_idx = beta1.find("function drawCAT6020B")
if cat_idx != -1:
    beta1 = beta1[:cat_idx]

combined_js = f"""
/* ============================================================================
 * SMART-KENISH 4.0 — 2.5D ISOMETRIC SCADA ENGINE (OPEN-PIT COPPER MINE)
 * Orchestrated by Antigravity (Chief Architect)
 * Generated by DeepSeek Subagents (Alpha: Terrain, Beta: Equipment, Gamma: X6 HUD)
 * Pure Native HTML5 Canvas 2D · Zero External CDN · 60 FPS CPU Friendly
 * ============================================================================ */

{alpha}

{beta1}

{beta2}

{gamma}
"""

with open("/tmp/deepseek_assembled.js", "w", encoding="utf-8") as f:
    f.write(combined_js)

print(f"Assembled script: {len(combined_js)} bytes. Checking syntax with node -c...")
res = subprocess.run(["node", "-c", "/tmp/deepseek_assembled.js"], capture_output=True, text=True)
if res.returncode == 0:
    print("SUCCESS: Assembled JavaScript syntax is 100% VALID!")
else:
    print("Syntax Error:", res.stderr)
